let currentLang = 'en';

export function initI18n() {
  const sysLang = navigator.language || navigator.userLanguage || 'en';
  // currentLang = sysLang.startsWith('zh') ? 'zh' : 'en';
  currentLang = 'en';
  applyLang();
}

export function setLang(lang) {
  if (lang !== 'zh' && lang !== 'en') return;
  currentLang = lang;
  localStorage.setItem('draftbox_lang', lang);
  applyLang();
}

function applyLang() {
  document.documentElement.lang = currentLang;

  // Update static DOM elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dictionary[currentLang][key]) {
      el.innerHTML = dictionary[currentLang][key]; // innerHTML to preserve svg elements if they are wrapped differently
    }
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (dictionary[currentLang][key]) {
      el.title = dictionary[currentLang][key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dictionary[currentLang][key]) {
      el.placeholder = dictionary[currentLang][key];
    }
  });
}

export function t(key) {
  return dictionary[currentLang][key] || key;
}

export function getCurrentLang() {
  return currentLang;
}
